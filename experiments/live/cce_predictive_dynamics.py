"""Benchmark a learned CCE state predictor against persistence.

This is a controlled research experiment, not a consciousness claim. The
synthetic trajectory is generated by a known dynamical process solely to test
whether the predictor can recover transition structure and beat the trivial
persistence baseline.
"""
from __future__ import annotations

import argparse
import json

import torch

from nsa.runtime.predictive_dynamics import StatePredictor, train_predictor


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--epochs", type=int, default=250)
    parser.add_argument("--samples", type=int, default=128)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    torch.manual_seed(19)
    states = torch.linspace(-1.5, 1.5, args.samples).unsqueeze(1)
    external = torch.sin(states * 2.0)
    targets = 0.72 * states + 0.18 * external + 0.05

    split = int(args.samples * 0.75)
    train_states, eval_states = states[:split], states[split:]
    train_external, eval_external = external[:split], external[split:]
    train_targets, eval_targets = targets[:split], targets[split:]

    model = StatePredictor(state_dim=1, input_dim=1, hidden_dim=32)
    train_predictor(
        model,
        train_states,
        train_targets,
        train_external,
        epochs=args.epochs,
        learning_rate=5e-3,
    )

    model.eval()
    with torch.no_grad():
        predictions = model(eval_states, eval_external)
    mse = float(torch.mean((predictions - eval_targets) ** 2))
    persistence = float(torch.mean((eval_states - eval_targets) ** 2))
    improvement = 0.0 if persistence == 0.0 else (persistence - mse) / persistence

    result = {
        "experiment": "cce_predictive_dynamics",
        "claim_boundary": "controlled transition-learning benchmark; no consciousness claim",
        "samples": args.samples,
        "epochs": args.epochs,
        "evaluation_mse": mse,
        "persistence_mse": persistence,
        "improvement_over_persistence": improvement,
        "beats_persistence": mse < persistence,
    }
    with open(args.output, "w", encoding="utf-8") as handle:
        json.dump(result, handle, indent=2)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
