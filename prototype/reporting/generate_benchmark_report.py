"""
prototype/reporting/generate_benchmark_report.py
======================================
Automated Benchmark Dashboard & Executive Report Generator for NSA.

Executes:
1. Systematic Ablation Study (Vanilla vs Security vs Confidence vs Product Algebra).
2. GPU Attention Overhead Benchmarks across sequence lengths T in [128, 512, 1024].
3. Empirical Red-Teaming Prompt Injection Defense Benchmarks.

Generates:
    docs/benchmark_report.md (Comprehensive Markdown Report with GitHub Alert formatting & tables)

Usage:
    python prototype/reporting/generate_benchmark_report.py [--output docs/benchmark_report.md]
"""

from __future__ import annotations

import argparse
import os
import sys
import time

import torch

# Ensure nsa is in python path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from prototype.experiments.ablation_study import run_ablation_study
from prototype.pillars.benchmark_gpu import run_gpu_benchmark
from prototype.pillars.prompt_injection_bench import run_prompt_injection_benchmark


def generate_markdown_report(
    ablation_results: list,
    gpu_results: list,
    injection_results: dict,
    output_path: str,
) -> None:
    """Format benchmark results into executive Markdown document."""

    report = f"""# Neural State Architecture (NSA) - Automated Benchmark Report Card

> **Generated on**: {time.strftime('%Y-%m-%d %H:%M:%S')}  
> **Target Framework**: PyTorch {torch.__version__} | Fused SDPA Attention Engine

---

## 1. Executive Summary & Four Pillars Validation

| Pillar Metric | Target Standard | Measured NSA Performance | Status |
| :--- | :--- | :--- | :---: |
| **Pillar 1: Quality Delta** | Toy LM PPL delta (not industrial scale) | See latest `make pretrain-lm` run | ⚠️ `TOY` |
| **Pillar 2: Latency Overhead** | SDPA fused mask overhead | See GPU table below | ⚠️ `MEASURED` |
| **Pillar 3: Base Retention** | Toy retrofit retention | See `make retrofit-lora` | ⚠️ `TOY` |
| **Pillar 4: Injection Proxy** | Synthetic secret-token proxy (not NL jailbreaks) | See red-team section | ⚠️ `TOY` |

---

## 2. Systematic Ablation Study

Evaluated across 4 structural configurations:
1. **Vanilla Transformer**: Standard un-governed Transformer.
2. **Security-Only**: Scalar security lattice governance ($\sigma \in \mathbb{{R}}^1$).
3. **Security + Confidence**: Dual security + Bayesian confidence bound tracking ($\sigma \in \mathbb{{R}}^2$).
4. **Full Product Algebra**: Complete Typed Neural Computation ($\Sigma = \Sigma_s \\times \Sigma_c \\times \Sigma_p \\times \Sigma_l$).

| Configuration | Latency (ms) | Throughput (tok/s) | Perplexity | ECE Calibration |
| :--- | :---: | :---: | :---: | :---: |
"""
    for res in ablation_results:
        cfg = res.get("name", "Config")
        lat = res.get("latency_ms", 0.0)
        tp = res.get("throughput", 0.0)
        ppl = res.get("perplexity", 0.0)
        ece = res.get("ece", 0.0)
        ppl_str = f"{ppl:.2e}" if ppl > 1e4 else f"{ppl:.2f}"
        report += f"| **{cfg}** | {lat:.2f} | {tp:.1f} | {ppl_str} | {ece:.4f} |\n"

    report += """
---

## 3. Fused GPU Attention Throughput & Scaling

Benchmarking `FusedStateAwareAttention` relative to vanilla PyTorch Scaled Dot-Product Attention across sequence lengths $T \in [128, 512, 1024]$:

| Sequence Length (T) | Vanilla Attention (ms) | Fused NSA Attention (ms) | Overhead Delta (%) | Speedup Over Naive 4D |
| :---: | :---: | :---: | :---: | :---: |
"""
    for res in gpu_results:
        seq = res.get("seq_len", 0)
        van = res.get("vanilla_lat", 0.0)
        fused = res.get("fused_lat", 0.0)
        delta = res.get("overhead_pct", 0.0)
        speedup = res.get("speedup_over_naive", 1.0)
        report += f"| **T = {seq}** | {van:.3f} | {fused:.3f} | {delta:+.2f}% | **{speedup:.2f}x Faster** |\n"

    report += f"""
---

## 4. Empirical Red-Teaming & Prompt Injection Defense

Adversarial evaluation testing indirect prompt injection payloads carrying `UNTRUSTED` state tags attempting to breach `SYSTEM` policies:

- **Total Adversarial Probes Evaluated**: `{injection_results.get('total_probes', 100)}`
- **Baseline Hijack Success Rate**: `{injection_results.get('base_hijack_rate_pct', float('nan')):.2f}%`
- **NSA Governed Hijack Rate**: `{injection_results.get('nsa_hijack_rate_pct', float('nan')):.2f}%`
- **System Policy Preservation**: `{injection_results.get('policy_retention_pct', float('nan')):.2f}%`
- **Final State Violation Rate**: `{injection_results.get('violation_rate_pct', float('nan')):.2f}%`
- **Metric note**: `{injection_results.get('metric_note', 'n/a')}`

---

> [!WARNING]
> Toy-scale automated report. Pillars are **not** industrial verifications. Insane PPL/ECE values indicate under-trained toy models, not production quality.
>
> *Generated by `prototype/reporting/generate_benchmark_report.py`.*
"""

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(report)
    print(f"\n✅ Benchmark report successfully generated at: {output_path}")


def main():
    parser = argparse.ArgumentParser(description="NSA Benchmark Report Generator")
    parser.add_argument("--output", type=str, default="docs/benchmark_report.md", help="Output path for Markdown report")
    parser.add_argument("--quick", action="store_true", help="Quick mode (fewer steps/epochs for fast generation)")
    args = parser.parse_args()

    steps = 10 if args.quick else 30
    epochs = 4 if args.quick else 8

    print("Step 1/3: Running Systematic Ablation Study...")
    ablation_results = run_ablation_study(num_steps=steps)

    print("\nStep 2/3: Running GPU Attention Throughput Benchmarks...")
    gpu_results = run_gpu_benchmark()

    print("\nStep 3/3: Running Empirical Red-Teaming Prompt Injection Benchmarks...")
    injection_results = run_prompt_injection_benchmark(epochs=epochs)

    print("\nSynthesizing Executive Markdown Report...")
    generate_markdown_report(ablation_results, gpu_results, injection_results, args.output)


if __name__ == "__main__":
    main()
